FEWSHOT_HEADER = """## 本群历史判定样例

以下是本群此前判定过的真实样例，用于对齐尺度。请勿照搬，只作参考。"""


def build_fewshots(positives, negatives, max_pos=8, max_neg=8) -> str:
    """构造 few-shot 段落。

    positives: 判为广告的样本（文本列表）
    negatives: 判为正常但曾被误判、或群友举报后被驳回的样本（反例）

    反例比正例更重要 —— V1 的学习是单向的（只从"已删除样本"学），
    导致规则越删越激进。这里强制带上反例作为纠正信号。
    """
    lines = [FEWSHOT_HEADER]
    if positives:
        lines.append("\n【判为广告的样例】")
        for text in positives[:max_pos]:
            lines.append(f"- {strip_invisibles(text)[:80]}")
    if negatives:
        lines.append("\n【判为正常的样例（含曾被误判的，务必放过）】")
        for text in negatives[:max_neg]:
            lines.append(f"- {strip_invisibles(text)[:80]}")
    if not positives and not negatives:
        return ""
    return "\n".join(lines)


def build_group_profile(
    title: str,
    chat_nature: str = "general",
    now: str = "",
    strictness: str = "strict",
) -> str:
    """构造群画像段落。chat_nature 取 NATURE_PRESETS 的 key。"""
    preset = NATURE_PRESETS.get(chat_nature, NATURE_PRESETS["general"])
    strictness_suffix = {
        "strict": "（严格档：只删除证据充分的广告）",
        "standard": "（标准档）",
        "loose": "（宽松档：宁可多删）",
    }.get(strictness, "")

    return GROUP_PROFILE_TEMPLATE.format(
        title=title or "未命名群",
        nature=preset["nature"],
        topics=preset["topics"],
        strictness_hint=preset["strictness_hint"] + strictness_suffix,
        now=now,
        nature_note=preset["nature_note"],
    )


